# 要望の言い方。「設問違い」（Q1）の行では、これを含まない言い換えを使う
REQUEST_WORDS = re.compile(r"ほしい|欲しい|望む|望み|もらいたい|希望|要望|求め|願|べき|してくれ|意見|提案|期待|声")


@dataclass(frozen=True, slots=True)
class Label:
    code: str
    name: str
    definition: str
    topics: tuple[str, ...]
    short: str
    keywords: tuple[str, ...]
    # キーワード違いの罠で使う語と、その語を入れさせる別の意味 [(語, 意味), ...]
    trap_keywords: tuple[tuple[str, str], ...] = ()
    # 設問違いの罠（Q3）用の、出来事・感想の形の言い換え。要望・意見・提案の形にしない
    report_topics: tuple[str, ...] = ()


@dataclass(frozen=True, slots=True)
class Question:
    qid: str
    column: str  # 入力ファイルの列名
    text: str  # 本文書き係に見せる設問文
    kind_shares: tuple[int, int, int, int]  # 中身あり／特になし／空欄／無効（0.1%単位）
    labels: tuple[Label, ...]
    label_shares: tuple[int, ...]
    pairs: tuple[tuple[str, str], ...]
    band_shares: tuple[int, ...]
    other_subjects: tuple[str, ...]
    # 「その他」の話題ごとの、読まれやすい近いカテゴリ（最大3つ）。(話題, (ラベル名, ...)) の並び
    other_near: tuple[tuple[str, tuple[str, ...]], ...] = ()
    negation_exclude: tuple[str, ...] = ()
    offq_exclude: tuple[str, ...] = ()
    sarcasm_exclude: tuple[str, ...] = ()

    def by_name(self, name: str) -> Label:
        for lb in self.labels:
            if lb.name == name:
                return lb
        raise KeyError(name)

    def request_free_topics(self, name: str) -> tuple[str, ...]:
        """要望の言い方を含まない言い換え。"""
        return tuple(t for t in self.by_name(name).topics if not REQUEST_WORDS.search(t))

    def offq_topics(self, name: str) -> tuple[str, ...]:
        """設問違いの罠で使える言い換え。Q1 は要望の言い方なし、Q3 は出来事・感想の形、Q2 は普通のもの。"""
        if self.qid == "Q1":
            return self.request_free_topics(name)
        if self.qid == "Q3":
            return self.by_name(name).report_topics
        return self.by_name(name).topics

    def near_categories(self, subject: str) -> tuple[str, ...]:
        """「その他」の話題から、本文が読まれやすい近いカテゴリ。「触れてはいけない話題」に先に入れる。"""
        for sub_, names in self.other_near:
            if sub_ == subject:
                return names
        raise KeyError(subject)

    def trap_meaning(self, name: str, word: str) -> str:
        for w, meaning in self.by_name(name).trap_keywords:
            if w == word:
                return meaning
        raise KeyError(word)

    def neighbors(self, name: str) -> list[str]:
        out = []
        for a, b in self.pairs:
            if a == name:
                out.append(b)
            elif b == name:
                out.append(a)
        return out


