"""Q1〜Q3 のコード表と、本文書き係に渡す話題の言い換え。

- `definition` はコード表（ground_truth/codeframe_q*.csv）に出す定義。
- `topics` は本文書き係に見せる言い換え。ラベル名・コード番号は含めない（テストで確かめる）。
- `short` は「触れてはいけない話題」「罠の話題」を短く言うときの言い方。
- `keywords` は「キーワードはあるが別カテゴリ」の罠で文中に出させる語。
"""

