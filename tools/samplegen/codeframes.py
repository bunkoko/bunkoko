def validate() -> None:
    """表の整合を確かめる（ラベル名の重複、関連ペアの綴り、割合の合計）。"""
    for q in QUESTIONS.values():
        names = [lb.name for lb in q.labels]
        if len(set(names)) != len(names):
            raise ValueError(f"{q.qid}: ラベル名が重複しています")
        if names[-1] != OTHER:
            raise ValueError(f"{q.qid}: 「その他」は最後に置きます")
        if len(q.label_shares) != len(q.labels) or sum(q.label_shares) != 1000:
            raise ValueError(f"{q.qid}: ラベルの割合が合いません")
        if sum(q.kind_shares) != 1000 or sum(q.band_shares) != 1000:
            raise ValueError(f"{q.qid}: 割合の合計が100%ではありません")
        for a, b in q.pairs:
            if a not in names or b not in names or OTHER in (a, b) or a == b:
                raise ValueError(f"{q.qid}: 関連ペアが不正です")
        for lb in q.labels:
            if not lb.topics or not lb.keywords:
                raise ValueError(f"{q.qid}: 話題の言い換えが空です")
            if q.qid == "Q1" and lb.name != OTHER and not q.request_free_topics(lb.name):
                raise ValueError(f"{q.qid}: 要望の言い方を含まない言い換えがありません")
        for lb in q.labels:
            if lb.name == OTHER:
                continue
            if not lb.trap_keywords or any(not w or not m for w, m in lb.trap_keywords):
                raise ValueError(f"{q.qid}: キーワード違いの語と意味がありません")
            if q.qid == "Q3" and lb.name not in q.offq_exclude:
                if not lb.report_topics or any(REQUEST_WORDS.search(t) for t in lb.report_topics):
                    raise ValueError(f"{q.qid}: 出来事・感想の形の言い換えが不正です")
        mapped = {k for k, _ in q.other_near}
        if mapped != set(q.other_subjects):
            raise ValueError(f"{q.qid}: 「その他」の話題と近いカテゴリの表が合いません")
        for _, near in q.other_near:
            if not 1 <= len(near) <= 3 or OTHER in near or any(n not in names for n in near):
                raise ValueError(f"{q.qid}: 近いカテゴリの指定が不正です")
        for n in (*q.negation_exclude, *q.offq_exclude, *q.sarcasm_exclude):
            if n not in names:
                raise ValueError(f"{q.qid}: 除外するラベル名が表にありません")
