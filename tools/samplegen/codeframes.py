def _labels(
    prefix_rows: list[tuple],
    trap_words: dict[str, list[tuple[str, str]]],
    report_topics: dict[str, list[str]] | None = None,
) -> tuple[Label, ...]:
    report_topics = report_topics or {}
    return tuple(
        Label(
            f"c{i:02d}",
            name,
            definition,
            tuple(topics),
            short,
            tuple(kw),
            tuple(trap_words.get(name, ())),
            tuple(report_topics.get(name, ())),
        )
        for i, (name, definition, topics, short, kw) in enumerate(prefix_rows, start=1)
    )


