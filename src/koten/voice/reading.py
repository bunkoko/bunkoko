        (rf"(?<=[{_STEM_HA}])(?<![{_K}][{_STEM_HA}])はう" + _END, "おう"),
        (rf"(?<=[{_STEM_HA}])(?<![{_K}][{_STEM_HA}])は" + _CONT_HA, "わ"),
