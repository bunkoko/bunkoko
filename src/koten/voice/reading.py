# 別名の括弧：2字以上の名前のすぐ後ろで、作品名『』か次の著者（・）の前か、行の終わりにあるもの
# （岡倉天心（岡倉覚三）『茶の本』）。中身は漢字とカタカナだけ（名前の形）。
# ひらがなを含むもの（冉有（ぜんゆう）の読み・「（セクハラ・パワハラを含む）」）、日付のあとの
# 曜日（四月三十日（土曜））、1字の語のあとの説明（彼（ナポレオン））は、別名と決まらないので残す
_ALIAS = re.compile(
    rf"(?<=[{_K}ァ-ヴー][{_K}ァ-ヴー])(?<![年月日])[（(]([{_K}ァ-ヴー・]{{2,20}})[）)](?=[『・\n]|$)"
)
_NOT_ALIAS = re.compile(r"[訳編著注校選撰作歳]$|[年月日曜]")
_SLASH = re.compile(  # 「1／2」のような数の間の斜線は区切りではないので残す
    r"[ \u3000]+[/／][ \u3000]*|[ \u3000]*[/／][ \u3000]+|(?<![0-9０-９])／(?![＼″0-9０-９])"
)
_SYMBOLS = str.maketrans("", "", "【】〔〕［］〈〉《》≪≫｜|※＊*★☆◆◇■□▲△▼▽●◎♪♫〓#＃→←↑↓⇒⇔")
_DASHES = re.compile(r"[―—─]+")
_SPACES = re.compile(r"[ \t\u3000]+")


def _drop_alias(m: re.Match[str]) -> str:
    return m.group(0) if _NOT_ALIAS.search(m.group(1)) else ""


def speech_text(text: str) -> str:
    """VOICEVOX に渡す前の整え。かぎかっこ「」『』はそのまま残す。

    - 別名の括弧を落とす（岡倉天心（岡倉覚三）『茶の本』→ 岡倉天心『茶の本』。訳者の括弧は残す）
    - 見出しの区切り「 / 」を「、」にする
    - 【】や記号（※・★・〓など）を除き、ダッシュ（――）は「、」にする
    - 連続する空白を1つに詰め、行の頭と終わりの空白・行の頭の読点を落とす。記号だけの行は落とす
      （行の終わりの読点は原文のものなので残す。段落をまとめて読むときの間になる）
    """
    text = _ALIAS.sub(_drop_alias, text)
    text = _SLASH.sub("、", text)
    text = text.translate(_SYMBOLS)
    text = _DASHES.sub("、", text)
    text = re.sub(r"、{2,}", "、", text)
    text = re.sub(r"、+(?=[。！？!?」』）])", "", text)
    text = re.sub(
        r"(?<=[「『（。！？!?])、+", "", text
    )  # 「。――」の――は文の切れ目なので読点にしない
    lines = []
    for line in text.split("\n"):
        line = _SPACES.sub(" ", line).strip(" ").lstrip("、 ")
        if line.strip("、 "):
            lines.append(line)
    return "\n".join(lines)


