def _is_kana(ch: str) -> bool:
    return "ぁ" <= ch <= "ゖ" or "ァ" <= ch <= "ヺ" or ch == "ー"


def _is_kanji(ch: str) -> bool:
    return bool(re.fullmatch(f"[{_K}]", ch))


