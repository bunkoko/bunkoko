        (r"きう(?=ござ|存)", "きゅう"),
        (r"たう(?=ござ|存)", "とう"),
        # ぢ・づ
        # それぢやうまく（じゃ＋上手く）、はなぢや（鼻血や）は直さない
        (r"(?<!はな)ぢや(?!う)", "じゃ"),
        (r"じや(?=な[いくか]|あ|ありま)", "じゃ"),  # 同じやうに は直さない
        (r"(?<=[恥閉怖綴捩])ぢ", "じ"),
        (r"はづ(?!き)", "はず"),  # 葉月（はづき）は今も はづき
        (r"(?<!い)づつ(?!み)", "ずつ"),  # 小包（こづつみ）・井筒（いづつ）は今も づ
