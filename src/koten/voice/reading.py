_SMALL = set("ぁぃぅぇぉゃゅょゎっァィゥェォャュョヮッ")
_PARTICLE_LIKE = set("をはがのにへとでもて")  # くの字点の前で、語の切れ目と分かる字


def _repeat_unit(out: list[str]) -> str | None:
    """くの字点の前の、繰り返す字（ふつうは2拍）。決められなければ None（開かない）。

    小さい字は前の字と合わせて1拍に数える（むしゃ〳〵→むしゃむしゃ、じゃら〳〵→じゃらじゃら）。
    """
    tail = "".join(out[-8:])
    for word in _LONG_UNITS:
        if tail.endswith(word):
            return word
    i = len(out)
    for _ in range(2):
        i -= 1
        while i > 0 and out[i] in _SMALL:
            i -= 1
        if i < 0 or out[i] in _SMALL:
            return None
    unit = out[i:]
    before = out[i - 1] if i > 0 else ""
    if unit[-1] in "りん" and "ぁ" <= before <= "ゖ" and before not in _PARTICLE_LIKE:
        return None  # 「ばさり〳〵」「きやん〳〵」は3字かもしれない（ありあり・どんどん は開く）
    if not _is_kana(unit[-1]) or not all(_is_kana(c) or _is_kanji(c) for c in unit):
        return None  # 「時〳〵」のように漢字の直後や、記号のあとは字数が決まらない
    if _is_kanji(unit[0]) and before and _is_kanji(before):
        return None  # 「途切れ〳〵」は2字か3字か分からない
    if all("ァ" <= c <= "ヺ" for c in unit + [before]):
        return None  # カタカナの擬音は3字のことが多い（カラン〳〵）。決められない
    return "".join(unit)


def _expand_odoriji(text: str) -> str:
    """踊り字を開く：こゝろ→こころ、たゞ→ただ、ます〳〵→ますます、しみ〴〵→しみじみ。"""
    text = text.replace("／″＼", "〴〵").replace("／＼", "〳〵").replace("〻", "々")
    out: list[str] = []
    i = 0
    while i < len(text):
        ch = text[i]
        pair = text[i : i + 2]
        if pair in ("〳〵", "〴〵") or ch in "〱〲":  # くの字点（2字ぶんの縦書きの記号、1字のもの）
            width = 2 if pair in ("〳〵", "〴〵") else 1
            unit = _repeat_unit(out)
            if unit is None:
                out.append(text[i : i + width])
            else:
                first = unit[0]
                if pair == "〴〵" or ch == "〲":
                    first = _VOICED.get(first, first)
                out.extend(first + unit[1:])
            i += width
            continue
        prev = out[-1] if out else ""
        base = _UNVOICED.get(prev, prev)
        if ch in "ゝヽ" and base in (_PLAIN_HIRA if ch == "ゝ" else _PLAIN_KATA):
            out.append(base)  # 「ゝ」は清音で繰り返す（などゝ→などと、こゝろ→こころ）
        elif ch in "ゞヾ" and (prev in _VOICED or prev in _UNVOICED):
            same_kind = ("ぁ" <= base <= "ゖ") == (ch == "ゞ")
            out.append(_VOICED[base] if same_kind else ch)
        else:
            out.append(ch)  # 漢字や「ん」のあとなど、繰り返し方が決まらないものはそのまま
        i += 1
    return "".join(out)


