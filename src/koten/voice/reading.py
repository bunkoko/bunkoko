        (rf"(?<=[{_K}])(?<![一二三四五六七八九十百千幾何])つ(?=て|た{_POST_TA})", "っ"),
        (rf"(?<=[あいうえきくさしだなまむもやよらわ])つ(?=て|た{_POST_TA})", "っ"),
