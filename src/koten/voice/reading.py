        (rf"(?<=[{_STEM}])ふ(?!た[つりた])", "う"),
        # 「へ」「は」は、前が漢字の熟語（宗教へ・時代へ・相違は）なら助詞なので直さない
        (rf"(?<=[{_STEM_HE}])(?<![{_K}][{_STEM_HE}])へ", "え"),
